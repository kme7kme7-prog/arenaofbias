import { createSandbox } from './sandbox.mjs';
import { runBrawl, createBrawl, buildBrawlPlayerState } from '../../app/tanks/engine/core/brawl.js';
import { PROFILE, ENGINE_HASH, RUNTIME_HASH, MAPS, SIDES } from './config.mjs';

// Only the trusted engine runs in Node; submitted source stays inside QuickJS.
process.once('disconnect', () => process.exit(1));
process.once('message', async workerData => {
const parentPort = { postMessage: value => process.send(value) };
try {
  if (workerData.kind === 'validate') {
    const bot = await createSandbox(workerData.source, 42);
    try {
      for (const map of MAPS) for (const side of SIDES) {
        const state = createBrawl(map.id, 42); state.tick = 100;
        bot.decide(buildBrawlPlayerState(state, side));
      }
    } finally { bot.dispose(); }
    parentPort.postMessage({ ok: true });
  } else {
    const { task, sources } = workerData;
    if (task.profile !== PROFILE || task.engineHash !== ENGINE_HASH || task.runtimeHash !== RUNTIME_HASH) throw Error('Execution profile mismatch');
    let index = 0;
    const result = await runBrawl({ mapId: task.mapId, seed: task.seed, seatSlots: task.seats,
      botSources: sources, adapterFactory: source => createSandbox(source, (task.seed ^ Math.imul(++index, 0x9e3779b9)) >>> 0) });
    result.meta.ladder = { profile: PROFILE, engineHash: ENGINE_HASH, runtimeHash: RUNTIME_HASH, versions: task.versions };
    // Error text is generated by the adapter; never persist guest source/stack.
    parentPort.postMessage({ ok: true, result });
  }
} catch { parentPort.postMessage({ ok: false, error: workerData.kind === 'validate' ? '运行检查未通过：请检查 decide(state)、动作格式及计算用量。' : '比赛执行中断或规则版本不一致，本场未计分。' }); }
});
